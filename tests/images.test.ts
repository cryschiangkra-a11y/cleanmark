import { describe, expect, test } from "vitest";
import { imageTags } from "../src/core/inspect/bytes";
import { placeholderPng, stripImageMetadata } from "../src/core/sanitize/images";
import { PNG_1PX } from "./fixtures/docx-builder";

const ascii = (s: string) => Uint8Array.from(s, (c) => c.charCodeAt(0));
const concat = (...parts: Uint8Array[]) => {
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let o = 0;
  for (const p of parts) (out.set(p, o), (o += p.length));
  return out;
};

/** 喺 PNG 嘅 IEND 之前插入一個 chunk（CRC 唔重要，清理器唔會檢查） */
function pngWithChunk(type: string, data: string): Uint8Array {
  const iendAt = PNG_1PX.length - 12;
  const len = new Uint8Array(4);
  new DataView(len.buffer).setUint32(0, data.length);
  return concat(PNG_1PX.slice(0, iendAt), len, ascii(type), ascii(data), new Uint8Array(4), PNG_1PX.slice(iendAt));
}

function chunkTypes(png: Uint8Array): string[] {
  const out: string[] = [];
  const dv = new DataView(png.buffer, png.byteOffset, png.byteLength);
  for (let o = 8; o < png.length; ) {
    const len = dv.getUint32(o);
    out.push(String.fromCharCode(...png.slice(o + 4, o + 8)));
    o += 12 + len;
  }
  return out;
}

describe("stripImageMetadata：PNG", () => {
  test("清走文字、EXIF、XMP、C2PA chunk，保留影像", () => {
    const dirty = [pngWithChunk("tEXt", "Software\0AI"), pngWithChunk("eXIf", "Exif\0\0"), pngWithChunk("caBX", "jumbc2pa")];
    for (const d of dirty) {
      const clean = stripImageMetadata(d, "png")!;
      expect(chunkTypes(clean)).toEqual(chunkTypes(PNG_1PX));
      expect(imageTags(clean)).toEqual([]);
    }
  });

  test("乾淨嘅 PNG 原封不動", () => {
    expect(stripImageMetadata(PNG_1PX, "png")).toEqual(PNG_1PX);
  });
});

describe("stripImageMetadata：JPEG", () => {
  const seg = (marker: number, body: string) => {
    const b = ascii(body);
    return concat(Uint8Array.of(0xff, marker, (b.length + 2) >> 8, (b.length + 2) & 0xff), b);
  };
  const SOI = Uint8Array.of(0xff, 0xd8);
  const scan = concat(Uint8Array.of(0xff, 0xda, 0x00, 0x02), Uint8Array.of(0x12, 0x34, 0xff, 0x00, 0x56), Uint8Array.of(0xff, 0xd9));

  test("清走 Exif、XMP、C2PA（APP11）同註解，保留 JFIF、ICC、影像資料", () => {
    const jpeg = concat(
      SOI,
      seg(0xe0, "JFIF\0\x01\x01"),
      seg(0xe1, "Exif\0\0data"),
      seg(0xe1, "http://ns.adobe.com/xap/1.0/\0<x/>"),
      seg(0xe2, "ICC_PROFILE\0\x01\x01prof"),
      seg(0xeb, "JPjumbc2pa"),
      seg(0xfe, "Generated by AI"),
      seg(0xdb, "quant"),
      scan,
    );
    const clean = stripImageMetadata(jpeg, "jpg")!;
    expect(clean).toEqual(concat(SOI, seg(0xe0, "JFIF\0\x01\x01"), seg(0xe2, "ICC_PROFILE\0\x01\x01prof"), seg(0xdb, "quant"), scan));
    expect(imageTags(clean)).toEqual([]);
  });

  test("唔係 JPEG 就回傳 null", () => {
    expect(stripImageMetadata(Uint8Array.of(1, 2, 3), "jpg")).toBeNull();
  });
});

describe("stripImageMetadata：GIF", () => {
  test("清走註解同 XMP 擴充，保留循環播放設定同影像", () => {
    const header = concat(ascii("GIF89a"), Uint8Array.of(1, 0, 1, 0, 0, 0, 0));
    const netscape = concat(Uint8Array.of(0x21, 0xff, 11), ascii("NETSCAPE2.0"), Uint8Array.of(3, 1, 0, 0, 0));
    const xmp = concat(Uint8Array.of(0x21, 0xff, 11), ascii("XMP DataXMP"), Uint8Array.of(4), ascii("<x/>"), Uint8Array.of(0));
    const comment = concat(Uint8Array.of(0x21, 0xfe, 5), ascii("hello"), Uint8Array.of(0));
    const image = Uint8Array.of(0x2c, 0, 0, 0, 0, 1, 0, 1, 0, 0, 2, 2, 0x4c, 0x01, 0);
    const gif = concat(header, netscape, xmp, comment, image, Uint8Array.of(0x3b));
    expect(stripImageMetadata(gif, "gif")).toEqual(concat(header, netscape, image, Uint8Array.of(0x3b)));
  });
});

test("placeholderPng 產生有效 PNG，冇任何標記", async () => {
  const png = await placeholderPng(1905000, 952500);
  expect(Array.from(png.slice(0, 8))).toEqual([137, 80, 78, 71, 13, 10, 26, 10]);
  expect(chunkTypes(png)).toEqual(["IHDR", "IDAT", "IEND"]);
  const dv = new DataView(png.buffer, png.byteOffset);
  expect([dv.getUint32(16), dv.getUint32(20)]).toEqual([400, 200]); // 按比例，最長一邊 400px
  expect(imageTags(png)).toEqual([]);
});

// ── WebP ─────────────────────────────────────────────

function riff(chunks: [string, Uint8Array][]): Uint8Array {
  const body = concat(
    ascii("WEBP"),
    ...chunks.map(([id, data]) => {
      const head = new Uint8Array(8);
      head.set(ascii(id));
      new DataView(head.buffer).setUint32(4, data.length, true);
      return concat(head, data, data.length % 2 ? new Uint8Array(1) : new Uint8Array(0));
    }),
  );
  const head = new Uint8Array(8);
  head.set(ascii("RIFF"));
  new DataView(head.buffer).setUint32(4, body.length, true);
  return concat(head, body);
}

function riffChunks(b: Uint8Array): string[] {
  const out: string[] = [];
  const dv = new DataView(b.buffer, b.byteOffset, b.byteLength);
  for (let o = 12; o + 8 <= b.length; ) {
    const len = dv.getUint32(o + 4, true);
    out.push(String.fromCharCode(...b.slice(o, o + 4)));
    o += 8 + len + (len % 2);
  }
  return out;
}

describe("stripImageMetadata：WebP", () => {
  test("清走 EXIF、XMP、C2PA、AIGC 資料段，同埋 VP8X 嘅標記；RIFF 大細要更新", () => {
    const vp8x = new Uint8Array(10);
    vp8x[0] = 0x08 | 0x04 | 0x20; // EXIF + XMP + ICC
    const webp = riff([
      ["VP8X", vp8x],
      ["ICCP", ascii("profile")],
      ["VP8L", ascii("pixels!")],
      ["EXIF", ascii("Exif\0\0AI")],
      ["XMP ", ascii("http://ns.adobe.com/xap/1.0/")],
      ["C2PA", ascii("jumbc2pa")],
      ["AIGC", ascii('{"Label":"1"}')],
    ]);
    const clean = stripImageMetadata(webp, "webp")!;
    expect(riffChunks(clean)).toEqual(["VP8X", "ICCP", "VP8L"]);
    expect(clean[20] & 0x0c).toBe(0); // EXIF、XMP 標記清走
    expect(clean[20] & 0x20).toBe(0x20); // ICC 標記保留
    expect(new DataView(clean.buffer, clean.byteOffset).getUint32(4, true)).toBe(clean.length - 8);
    expect(imageTags(clean)).toEqual([]);
  });

  test("唔係 WebP 就回傳 null", () => {
    expect(stripImageMetadata(ascii("RIFF\0\0\0\0WAVE"), "webp")).toBeNull();
  });
});

// ── TIFF ─────────────────────────────────────────────

/** 砌一個小端序 TIFF：一個 IFD，加一個 EXIF 子 IFD */
function tiff(): Uint8Array {
  const buf = new Uint8Array(512);
  const dv = new DataView(buf.buffer);
  buf.set(ascii("II*\0"));
  dv.setUint32(4, 8, true);
  const desc = ascii("AI generated by SomeTool\0");
  const xmp = ascii("http://ns.adobe.com/xap/1.0/ AI");
  const pixels = Uint8Array.of(1, 2, 3, 4);
  const entries: [number, number, number, number][] = [
    [256, 3, 1, 2], // ImageWidth
    [257, 3, 1, 2], // ImageLength
    [258, 3, 1, 8], // BitsPerSample
    [259, 3, 1, 1], // Compression
    [262, 3, 1, 1], // Photometric
    [270, 2, desc.length, 300], // ImageDescription → 300
    [273, 4, 1, 400], // StripOffsets → 400
    [277, 3, 1, 1], // SamplesPerPixel
    [278, 3, 1, 2], // RowsPerStrip
    [279, 4, 1, 4], // StripByteCounts
    [305, 2, 4, 0x00494100], // Software "AI\0"（4 bytes 內嵌）
    [700, 1, xmp.length, 340], // XMP → 340
    [34665, 4, 1, 200], // Exif IFD → 200
  ];
  dv.setUint16(8, entries.length, true);
  entries.forEach(([tag, type, count, value], i) => {
    const o = 10 + i * 12;
    dv.setUint16(o, tag, true);
    dv.setUint16(o + 2, type, true);
    dv.setUint32(o + 4, count, true);
    if (type === 3 && count === 1) dv.setUint16(o + 8, value, true);
    else dv.setUint32(o + 8, value, true);
  });
  dv.setUint32(10 + entries.length * 12, 0, true);
  // EXIF 子 IFD：UserComment（37510）→ 260
  dv.setUint16(200, 1, true);
  dv.setUint16(202, 37510, true);
  dv.setUint16(204, 7, true);
  dv.setUint32(206, 12, true);
  dv.setUint32(210, 260, true);
  dv.setUint32(214, 0, true);
  buf.set(ascii("ASCII\0\0\0AI!!"), 260);
  buf.set(desc, 300);
  buf.set(xmp, 340);
  buf.set(pixels, 400);
  return buf;
}

function tiffTags(b: Uint8Array): number[] {
  const dv = new DataView(b.buffer, b.byteOffset);
  const ifd = dv.getUint32(4, true);
  return Array.from({ length: dv.getUint16(ifd, true) }, (_, i) => dv.getUint16(ifd + 2 + i * 12, true));
}

describe("stripImageMetadata：TIFF", () => {
  test("清走描述、軟件、XMP、EXIF 標籤，資料清零；影像資料唔郁", () => {
    const original = tiff();
    expect(imageTags(original)).toEqual(expect.arrayContaining(["exif", "xmp"]));
    const clean = stripImageMetadata(original, "tiff")!;
    expect(tiffTags(clean)).toEqual([256, 257, 258, 259, 262, 273, 277, 278, 279]);
    const text = new TextDecoder("latin1").decode(clean);
    for (const s of ["AI generated", "ns.adobe.com", "AI!!"]) expect(text, s).not.toContain(s);
    expect(Array.from(clean.slice(400, 404))).toEqual([1, 2, 3, 4]);
    expect(imageTags(clean)).toEqual([]);
  });

  test("唔係 TIFF 就回傳 null", () => {
    expect(stripImageMetadata(ascii("hello"), "tiff")).toBeNull();
  });
});
